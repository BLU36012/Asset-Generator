import type { MeshData } from '../generators/types';
import { materialNames, num, textureFileName, type ExportedFile } from './util';
import { zip, type ZipEntry } from './zip';

/** Builds the .obj and .mtl text. `scale` converts meters to the target engine's units. */
export function buildObj(mesh: MeshData, base: string, scale: number): { obj: string; mtl: string } {
  const names = materialNames(mesh);
  const lines = ['# Generated by Asset Generator', `mtllib ${base}.mtl`, `o ${base}`];
  let offset = 1; // OBJ indices are 1-based and global across the file

  for (const part of mesh.parts) {
    lines.push(`g ${names[part.material]}`);
    for (let i = 0; i < part.positions.length; i += 3) {
      lines.push(`v ${num(part.positions[i] * scale)} ${num(part.positions[i + 1] * scale)} ${num(part.positions[i + 2] * scale)}`);
    }
    // OBJ's V axis points up; ours (glTF) points down.
    for (let i = 0; i < part.uvs.length; i += 2) lines.push(`vt ${num(part.uvs[i])} ${num(1 - part.uvs[i + 1])}`);
    for (let i = 0; i < part.normals.length; i += 3) {
      lines.push(`vn ${num(part.normals[i])} ${num(part.normals[i + 1])} ${num(part.normals[i + 2])}`);
    }
    lines.push(`usemtl ${names[part.material]}`);
    for (let i = 0; i < part.indices.length; i += 3) {
      const [a, b, c] = [part.indices[i] + offset, part.indices[i + 1] + offset, part.indices[i + 2] + offset];
      lines.push(`f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}`);
    }
    offset += part.positions.length / 3;
  }

  const mtl = ['# Generated by Asset Generator'];
  mesh.materials.forEach((m, i) => {
    mtl.push(
      '',
      `newmtl ${names[i]}`,
      'Ka 0 0 0',
      `Kd ${num(m.color[0])} ${num(m.color[1])} ${num(m.color[2])}`,
      `Ks ${num(m.metallic * 0.5 + 0.05)} ${num(m.metallic * 0.5 + 0.05)} ${num(m.metallic * 0.5 + 0.05)}`,
      `Ns ${num((1 - m.roughness) * 200 + 10)}`,
      'd 1',
      'illum 2',
    );
    if (m.emissive) mtl.push(`Ke ${num(m.emissive[0])} ${num(m.emissive[1])} ${num(m.emissive[2])}`);
    if (m.textured && mesh.texture) mtl.push(`map_Kd ${textureFileName(base)}`);
  });

  return { obj: lines.join('\n') + '\n', mtl: mtl.join('\n') + '\n' };
}

export async function toObjZip(mesh: MeshData, base: string, scale: number): Promise<ExportedFile> {
  const { obj, mtl } = buildObj(mesh, base, scale);
  const entries: ZipEntry[] = [
    { name: `${base}.obj`, data: obj },
    { name: `${base}.mtl`, data: mtl },
  ];
  if (mesh.texture) entries.push({ name: textureFileName(base), data: mesh.texture.png });
  return { data: await zip(entries), fileName: `${base}_obj.zip`, mime: 'application/zip' };
}
