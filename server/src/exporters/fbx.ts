import type { MeshData } from '../generators/types';
import { materialNames, num, textureFileName, type ExportedFile } from './util';
import { zip } from './zip';

// Fixed object IDs; there is only ever one model and geometry per file.
const GEOMETRY_ID = 1000;
const MODEL_ID = 2000;
const MATERIAL_BASE_ID = 3000;
const TEXTURE_ID = 4000;
const VIDEO_ID = 5000;

/** Writes `a: v,v,v` wrapped across lines the way Autodesk's own ASCII exporter does. */
function arrayProp(indent: string, key: string, values: (number | string)[]): string {
  const chunks: string[] = [];
  for (let i = 0; i < values.length; i += 24) chunks.push(values.slice(i, i + 24).join(','));
  return `${indent}${key}: *${values.length} {\n${indent}\ta: ${chunks.join(',\n' + indent + '\t')}\n${indent}}`;
}

/**
 * ASCII FBX 7.4 with one mesh, per-polygon materials and an external PNG texture.
 * Geometry is in meters; UnitScaleFactor=100 tells importers 1 unit = 100 cm.
 */
export function buildFbx(mesh: MeshData, base: string): string {
  const matNames = materialNames(mesh);
  const vertices: string[] = [];
  const polygonIndex: number[] = [];
  const normals: string[] = [];
  const uvs: string[] = [];
  const uvIndex: number[] = [];
  const polyMaterials: number[] = [];

  let offset = 0;
  for (const part of mesh.parts) {
    for (const v of part.positions) vertices.push(num(v));
    for (const n of part.normals) normals.push(num(n));
    for (let i = 0; i < part.uvs.length; i += 2) uvs.push(num(part.uvs[i]), num(1 - part.uvs[i + 1]));
    for (let i = 0; i < part.indices.length; i += 3) {
      const [a, b, c] = [part.indices[i] + offset, part.indices[i + 1] + offset, part.indices[i + 2] + offset];
      // The last index of each polygon is stored as -(index + 1).
      polygonIndex.push(a, b, ~c);
      uvIndex.push(a, b, c);
      polyMaterials.push(part.material);
    }
    offset += part.positions.length / 3;
  }

  const textured = Boolean(mesh.texture) && mesh.materials.some((m) => m.textured);
  const tex = textureFileName(base);
  const now = new Date();
  const pad = (n: number, w = 2) => String(n).padStart(w, '0');

  const materials = mesh.materials
    .map(
      (m, i) => `\tMaterial: ${MATERIAL_BASE_ID + i}, "Material::${matNames[i]}", "" {
\t\tVersion: 102
\t\tShadingModel: "phong"
\t\tMultiLayer: 0
\t\tProperties70:  {
\t\t\tP: "DiffuseColor", "Color", "", "A",${num(m.color[0])},${num(m.color[1])},${num(m.color[2])}
\t\t\tP: "DiffuseFactor", "Number", "", "A",1
\t\t\tP: "SpecularColor", "Color", "", "A",${num(m.metallic)},${num(m.metallic)},${num(m.metallic)}
\t\t\tP: "Shininess", "Number", "", "A",${num((1 - m.roughness) * 100)}${
        m.emissive
          ? `
\t\t\tP: "EmissiveColor", "Color", "", "A",${num(m.emissive[0])},${num(m.emissive[1])},${num(m.emissive[2])}
\t\t\tP: "EmissiveFactor", "Number", "", "A",1`
          : ''
      }
\t\t}
\t}`,
    )
    .join('\n');

  const textureObjects = textured
    ? `
\tVideo: ${VIDEO_ID}, "Video::${base}_texture", "Clip" {
\t\tType: "Clip"
\t\tProperties70:  {
\t\t\tP: "Path", "KString", "XRefUrl", "", "${tex}"
\t\t}
\t\tUseMipMap: 0
\t\tFilename: "${tex}"
\t\tRelativeFilename: "${tex}"
\t}
\tTexture: ${TEXTURE_ID}, "Texture::${base}_texture", "" {
\t\tType: "TextureVideoClip"
\t\tVersion: 202
\t\tTextureName: "Texture::${base}_texture"
\t\tMedia: "Video::${base}_texture"
\t\tFileName: "${tex}"
\t\tRelativeFilename: "${tex}"
\t\tModelUVTranslation: 0,0
\t\tModelUVScaling: 1,1
\t\tTexture_Alpha_Source: "None"
\t\tCropping: 0,0,0,0
\t}`
    : '';

  const connections = [
    `\tC: "OO",${MODEL_ID},0`,
    `\tC: "OO",${GEOMETRY_ID},${MODEL_ID}`,
    ...mesh.materials.map((_, i) => `\tC: "OO",${MATERIAL_BASE_ID + i},${MODEL_ID}`),
  ];
  if (textured) {
    mesh.materials.forEach((m, i) => {
      if (m.textured) connections.push(`\tC: "OP",${TEXTURE_ID},${MATERIAL_BASE_ID + i}, "DiffuseColor"`);
    });
    connections.push(`\tC: "OO",${VIDEO_ID},${TEXTURE_ID}`);
  }

  const objectCount = 3 + mesh.materials.length + (textured ? 2 : 0);

  return `; FBX 7.4.0 project file
; Generated by Asset Generator
; ----------------------------------------------------

FBXHeaderExtension:  {
\tFBXHeaderVersion: 1003
\tFBXVersion: 7400
\tCreationTimeStamp:  {
\t\tVersion: 1000
\t\tYear: ${now.getUTCFullYear()}
\t\tMonth: ${now.getUTCMonth() + 1}
\t\tDay: ${now.getUTCDate()}
\t\tHour: ${now.getUTCHours()}
\t\tMinute: ${now.getUTCMinutes()}
\t\tSecond: ${now.getUTCSeconds()}
\t\tMillisecond: 0
\t}
\tCreator: "Asset Generator"
}
CreationTime: "${now.getUTCFullYear()}-${pad(now.getUTCMonth() + 1)}-${pad(now.getUTCDate())} ${pad(now.getUTCHours())}:${pad(now.getUTCMinutes())}:${pad(now.getUTCSeconds())}:000"
Creator: "Asset Generator"

GlobalSettings:  {
\tVersion: 1000
\tProperties70:  {
\t\tP: "UpAxis", "int", "Integer", "",1
\t\tP: "UpAxisSign", "int", "Integer", "",1
\t\tP: "FrontAxis", "int", "Integer", "",2
\t\tP: "FrontAxisSign", "int", "Integer", "",1
\t\tP: "CoordAxis", "int", "Integer", "",0
\t\tP: "CoordAxisSign", "int", "Integer", "",1
\t\tP: "OriginalUpAxis", "int", "Integer", "",1
\t\tP: "OriginalUpAxisSign", "int", "Integer", "",1
\t\tP: "UnitScaleFactor", "double", "Number", "",100
\t\tP: "OriginalUnitScaleFactor", "double", "Number", "",100
\t}
}

Definitions:  {
\tVersion: 100
\tCount: ${objectCount}
\tObjectType: "GlobalSettings" {
\t\tCount: 1
\t}
\tObjectType: "Model" {
\t\tCount: 1
\t}
\tObjectType: "Geometry" {
\t\tCount: 1
\t}
\tObjectType: "Material" {
\t\tCount: ${mesh.materials.length}
\t}${
    textured
      ? `
\tObjectType: "Texture" {
\t\tCount: 1
\t}
\tObjectType: "Video" {
\t\tCount: 1
\t}`
      : ''
  }
}

Objects:  {
\tGeometry: ${GEOMETRY_ID}, "Geometry::${base}", "Mesh" {
${arrayProp('\t\t', 'Vertices', vertices)}
${arrayProp('\t\t', 'PolygonVertexIndex', polygonIndex)}
\t\tGeometryVersion: 124
\t\tLayerElementNormal: 0 {
\t\t\tVersion: 101
\t\t\tName: ""
\t\t\tMappingInformationType: "ByVertice"
\t\t\tReferenceInformationType: "Direct"
${arrayProp('\t\t\t', 'Normals', normals)}
\t\t}
\t\tLayerElementUV: 0 {
\t\t\tVersion: 101
\t\t\tName: "UVMap"
\t\t\tMappingInformationType: "ByPolygonVertex"
\t\t\tReferenceInformationType: "IndexToDirect"
${arrayProp('\t\t\t', 'UV', uvs)}
${arrayProp('\t\t\t', 'UVIndex', uvIndex)}
\t\t}
\t\tLayerElementMaterial: 0 {
\t\t\tVersion: 101
\t\t\tName: ""
\t\t\tMappingInformationType: "ByPolygon"
\t\t\tReferenceInformationType: "IndexToDirect"
${arrayProp('\t\t\t', 'Materials', polyMaterials)}
\t\t}
\t\tLayer: 0 {
\t\t\tVersion: 100
\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementNormal"
\t\t\t\tTypedIndex: 0
\t\t\t}
\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementMaterial"
\t\t\t\tTypedIndex: 0
\t\t\t}
\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementUV"
\t\t\t\tTypedIndex: 0
\t\t\t}
\t\t}
\t}
\tModel: ${MODEL_ID}, "Model::${base}", "Mesh" {
\t\tVersion: 232
\t\tProperties70:  {
\t\t\tP: "Lcl Translation", "Lcl Translation", "", "A",0,0,0
\t\t\tP: "Lcl Rotation", "Lcl Rotation", "", "A",0,0,0
\t\t\tP: "Lcl Scaling", "Lcl Scaling", "", "A",1,1,1
\t\t\tP: "DefaultAttributeIndex", "int", "Integer", "",0
\t\t}
\t\tShading: T
\t\tCulling: "CullingOff"
\t}
${materials}${textureObjects}
}

Connections:  {
${connections.join('\n')}
}
`;
}

/** Plain .fbx when untextured; otherwise .fbx + texture PNG zipped together. */
export async function toFbx(mesh: MeshData, base: string): Promise<ExportedFile> {
  const fbx = buildFbx(mesh, base);
  if (!mesh.texture || !mesh.materials.some((m) => m.textured)) {
    return { data: Buffer.from(fbx, 'utf8'), fileName: `${base}.fbx`, mime: 'application/octet-stream' };
  }
  const data = await zip([
    { name: `${base}.fbx`, data: fbx },
    { name: textureFileName(base), data: mesh.texture.png },
  ]);
  return { data, fileName: `${base}_fbx.zip`, mime: 'application/zip' };
}
